// Render the giscus comment themes for Weekly and the blog from one template,
// so the three files differ only by tokens. The blog's giscus include points
// at /styles/giscus-blog.css on this site. Pass --check to fail on drift.
import { readFile, writeFile } from "node:fs/promises";

const root = new URL("../", import.meta.url);
const read = (path) => readFile(new URL(path, root), "utf8");

const lightStatus = {
  success: "#1a7f37",
  attention: "#9a6700",
  attention_muted: "#d4a72c66",
  attention_subtle: "#fff8c5",
  danger: "#d1242f",
  danger_muted: "#ff818266",
  danger_subtle: "#ffebe9",
};
const darkStatus = {
  success: "#3fb950",
  attention: "#d29922",
  attention_muted: "#bb800966",
  attention_subtle: "#bb800926",
  danger: "#f85149",
  danger_muted: "#f8514966",
  danger_subtle: "#f851491a",
};

// Links take the accent; the login and submit button take btn, so the dark
// theme can keep its orange links without an orange button.
const themes = {
  "giscus-light.css": {
    scheme: "light", status: lightStatus,
    bg: "#fff", text: "#262626", muted: "#666", subtle: "#767676", line: "#ebebeb",
    fill: "#f5f5f5", fill_hover: "#ededed", accent: "#a67c52",
    reacted: "rgb(166 124 82 / 10%)", reacted_hover: "rgb(166 124 82 / 16%)",
    btn: "#a67c52", btn_text: "#fff", btn_disabled: "#d3bea9", btn_disabled_text: "#fffc", btn_radius: "999px",
  },
  "giscus-dark.css": {
    scheme: "dark", status: darkStatus,
    bg: "#21262b", text: "#e7e9ea", muted: "#a9aeb3", subtle: "#8b949e", line: "#343a40",
    fill: "#2a3035", fill_hover: "#323940", accent: "#e8a15a",
    reacted: "rgb(232 161 90 / 14%)", reacted_hover: "rgb(232 161 90 / 20%)",
    btn: "#e7e9ea", btn_text: "#21262b", btn_disabled: "#4a5157", btn_disabled_text: "#a9aeb3", btn_radius: "999px",
  },
  "giscus-blog.css": {
    scheme: "light", status: lightStatus,
    bg: "#fff", text: "#24292f", muted: "#666", subtle: "#767676", line: "#ebebeb",
    fill: "#f5f5f5", fill_hover: "#ededed", accent: "#222",
    reacted: "rgb(34 34 34 / 7%)", reacted_hover: "rgb(34 34 34 / 12%)",
    btn: "#222", btn_text: "#fff", btn_disabled: "#9a9a9a", btn_disabled_text: "#fffc",
    // tw93.fun's $border-radius, the corner of its 邮件订阅 and 支持作者 buttons.
    btn_radius: "8px",
  },
};

const template = await read("scripts/templates/giscus-theme.css");
const fonts = (await read("public/fonts/jinkai.css")).trim();
const syntax = {
  light: await read("scripts/assets/giscus-syntax-light.css"),
  dark: await read("scripts/assets/giscus-syntax-dark.css"),
};

const render = ({ status, ...tokens }) => {
  const values = {
    ...tokens,
    ...Object.fromEntries(Object.entries(status).map(([key, value]) => [`status_${key}`, value])),
    header: `/* giscus theme, generated by scripts/generate-giscus-themes.js from
   scripts/templates/giscus-theme.css; edit those and rerun, not this file.
   Variables follow giscus.app/themes/${tokens.scheme}.css. */`,
    fonts: `/* The @font-face rules of /fonts/jinkai.css, inlined so the widget does not wait
   for a second stylesheet before it can paint. */\n${fonts}\n`,
    syntax: syntax[tokens.scheme].split("\n").filter((line) => line.startsWith("  --")).join("\n"),
  };
  return template.replace(/\{\{(\w+)\}\}/g, (_, key) => {
    if (!(key in values)) throw new Error(`giscus theme template: no token ${key}`);
    return values[key];
  });
};

const check = process.argv.includes("--check");
const stale = [];
for (const [name, tokens] of Object.entries(themes)) {
  const path = `public/styles/${name}`;
  const css = render(tokens);
  if (!check) await writeFile(new URL(path, root), css);
  else if ((await read(path).catch(() => "")) !== css) stale.push(path);
}
if (stale.length) {
  console.error(`Out of date, run node scripts/generate-giscus-themes.js: ${stale.join(", ")}`);
  process.exit(1);
}
